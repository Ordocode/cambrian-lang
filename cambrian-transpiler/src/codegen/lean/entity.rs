fn emit_local_aliases(out: &mut String, entity: &Entity, profile: LeanProfile) {
    for ta in &entity.type_aliases {
        // Always inline. Lean has `abbrev` for transparent aliases;
        // we use it so downstream code never sees the alias.
        out.push_str(&format!(
            "abbrev {} : Type := {}\n",
            ta.name,
            lower_alias_target(ta, entity, profile),
        ));
    }
    if !entity.type_aliases.is_empty() {
        out.push('\n');
    }
}

fn lower_alias_target(ta: &TypeAlias, entity: &Entity, profile: LeanProfile) -> String {
    // Use a tiny local LeanTypeCtx — alias targets reference only
    // primitives + types declared in the same entity (or top level).
    let prog = empty_program_singleton();
    let ctx = LeanTypeCtx::for_entity(
        leak_program(prog),
        &entity.name,
        &entity.records,
        &entity.enums,
        &entity.type_aliases,
        profile,
    );
    lower_type(&ta.ty, &ctx)
}

/// Emit local records + enums in dependency order so a record that
/// references a local enum (or vice versa) is never forward-referenced
/// (Lean rejects forward refs outside a `mutual` block).
fn emit_local_types_ordered(
    out: &mut String,
    program: &Program,
    entity: &Entity,
    profile: LeanProfile,
) {
    let graphs = crate::analysis::ProgramGraphs::build(program);
    for item in graphs.resolve_entity_types(entity) {
        match item {
            super::core::types::TypeItem::Record(rec) => {
                emit_record(out, program, entity, rec, profile)
            }
            super::core::types::TypeItem::Enum(en) => emit_enum(out, entity, en, profile),
        }
    }
}

fn emit_record(
    out: &mut String,
    program: &Program,
    entity: &Entity,
    rec: &Record,
    profile: LeanProfile,
) {
    doc_comment(out, 0, &format!("Local record `{}`.", rec.name));
    out.push_str(&format!("structure {} where\n", lean_local_type_name(&rec.name)));
    let ctx = LeanTypeCtx::for_entity(
        program,
        &entity.name,
        &entity.records,
        &entity.enums,
        &entity.type_aliases,
        profile,
    );
    for f in &rec.fields {
        push_indent(out, 1);
        out.push_str(&format!(
            "{} : {}\n",
            super::core::types::lean_safe_ident(&f.name),
            lower_type(&f.ty, &ctx)
        ));
    }
    let derives = super::core::deceq::instances_filtered(
        ctx.use_predictable_profile,
        true,
        true,
        &["Repr", "Inhabited", "BEq", "DecidableEq"],
    );
    push_deriving(out, ctx.use_predictable_profile, &derives);
    let field_names: Vec<String> = rec
        .fields
        .iter()
        .map(|f| super::core::types::lean_safe_ident(&f.name))
        .collect();
    super::evm::maybe_emit_struct_eq_instances(
        out,
        ctx.use_predictable_profile,
        &lean_local_type_name(&rec.name),
        &field_names,
    );
}

fn emit_enum(out: &mut String, entity: &Entity, en: &EnumDecl, profile: LeanProfile) {
    doc_comment(out, 0, &format!("Local enum `{}`.", en.name));
    out.push_str(&format!("inductive {} where\n", lean_local_type_name(&en.name)));
    let prog = empty_program_singleton();
    let ctx = LeanTypeCtx::for_entity(
        leak_program(prog),
        &entity.name,
        &entity.records,
        &entity.enums,
        &entity.type_aliases,
        profile,
    );
    for v in &en.variants {
        emit_enum_variant(out, &lean_local_type_name(&en.name), v, &ctx);
    }
    let ctors: Vec<(String, usize)> = en
        .variants
        .iter()
        .map(|v| (sanitize_variant(&v.name), v.fields.len()))
        .collect();
    // Data-carrying enum: drop the matcher-minting `deriving BEq` and emit an
    // explicit Bool matrix (P4, see `lean_pure::emit_top_level_enum`); nullary
    // enum keeps `deriving BEq` (a `ctorIdx` comparison — predictable).
    let is_data = ctors.iter().any(|(_, arity)| *arity > 0);
    let derives = super::core::deceq::instances_filtered(
        ctx.use_predictable_profile,
        true,
        is_data,
        &["Repr", "Inhabited", "BEq", "DecidableEq"],
    );
    push_deriving(out, ctx.use_predictable_profile, &derives);
    super::evm::maybe_emit_enum_eq_instances(
        out,
        ctx.use_predictable_profile,
        &lean_local_type_name(&en.name),
        &ctors,
        is_data,
    );
}

fn emit_enum_variant(out: &mut String, _enum_name: &str, v: &EnumVariant, ctx: &LeanTypeCtx<'_>) {
    push_indent(out, 1);
    if v.fields.is_empty() {
        out.push_str(&format!("| {}\n", sanitize_variant(&v.name)));
    } else {
        let parts: Vec<String> = v.fields.iter().map(|t| lower_type(t, ctx)).collect();
        out.push_str(&format!(
            "| {} : {} → {}\n",
            sanitize_variant(&v.name),
            parts.join(" → "),
            _enum_name,
        ));
    }
}

fn emit_constants(out: &mut String, program: &Program, entity: &Entity, profile: LeanProfile) {
    if entity.constants.is_empty() {
        return;
    }
    let type_ctx = LeanTypeCtx::for_entity(
        program,
        &entity.name,
        &entity.records,
        &entity.enums,
        &entity.type_aliases,
        profile,
    );
    let expr_ctx = LeanExprCtx {
        type_ctx: LeanTypeCtx {
            program: type_ctx.program,
            proof_helpers: type_ctx.proof_helpers,
            use_nat_numerics: type_ctx.use_nat_numerics,
            overflow_panic: type_ctx.overflow_panic,
            use_predictable_profile: type_ctx.use_predictable_profile,
            deterministic_addresses: type_ctx.deterministic_addresses,
            entity_name: type_ctx.entity_name,
            local_records: type_ctx.local_records,
            local_enums: type_ctx.local_enums,
            local_aliases: type_ctx.local_aliases,
        },
        entity,
        local_enums: &entity.enums,
        pure_fns: &program.pure_fns,
        lets: HashSet::new(),
        route_params: HashSet::new(),
        route_name: None,
        phase_name: None,
        route_arg_names: vec![],
        in_transform: false,
        state_var: "s".to_string(),
        derived_helpers: HashSet::new(),
        world_var: None,
        instance_var: None,
        qualified_instances: std::collections::HashMap::new(),
        deploy_bindings: std::collections::HashMap::new(),
        hashmap_idents: std::collections::HashSet::new(),
        nat_idents: std::collections::HashSet::new(),
        trace_acc_var: None,
        expected_bitvec_width: None,
        expected_signed: None,
        expected_collection: None,
        msg_sender_override: None,
        pure_fn: None,
    };
    for c in &entity.constants {
        out.push_str(&format!(
            "def {} : {} := {}\n",
            c.name,
            lower_type(&c.ty, &type_ctx),
            gen_expr(&c.value, &expr_ctx),
        ));
    }
    out.push('\n');
}

// ---------------------------------------------------------------------------
// helpers — leak a tiny empty Program so we can build a LeanTypeCtx for
// alias-target / enum lowering without threading the program everywhere.
// Safe because the leaked allocation is small and per-call.
// ---------------------------------------------------------------------------

fn empty_program_singleton() -> Program {
    Program {
        imports: vec![],
        file_imports: vec![],
        pure_fns: vec![],
        type_aliases: vec![],
        records: vec![],
        enums: vec![],
        entities: vec![],
        extern_entities: vec![],
        tests: vec![],
        properties: vec![],
        fuzz_tests: vec![],
        invariants: vec![],
        events: vec![],
        errors: vec![],
        libraries: vec![],
        using_decls: vec![],
    }
}

fn leak_program(p: Program) -> &'static Program {
    Box::leak(Box::new(p))
}
